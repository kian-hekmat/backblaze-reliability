-- 20_load.sql
-- Loads gold Parquet files (already in @EXPORTS_STAGE via `snow stage copy`, see load_gold.sh).
-- Idempotent: each table is truncated, then fully reloaded with COPY ... MATCH_BY_COLUMN_NAME.
-- FORCE = TRUE so a reload of identically named files is not skipped by load metadata.

USE ROLE LOADER;
USE SECONDARY ROLES NONE;
USE WAREHOUSE LOAD_WH;
USE SCHEMA BACKBLAZE.GOLD;

CREATE FILE FORMAT IF NOT EXISTS PARQUET_FF TYPE = PARQUET;

TRUNCATE TABLE IF EXISTS DRIVE_LIFETIMES;
COPY INTO DRIVE_LIFETIMES FROM @EXPORTS_STAGE/drive_lifetimes/
  FILE_FORMAT = (FORMAT_NAME = PARQUET_FF) PATTERN = '.*[.]parquet'
  MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE FORCE = TRUE ON_ERROR = ABORT_STATEMENT;

TRUNCATE TABLE IF EXISTS MODEL_PERIOD_STATS;
COPY INTO MODEL_PERIOD_STATS FROM @EXPORTS_STAGE/model_period_stats/
  FILE_FORMAT = (FORMAT_NAME = PARQUET_FF) PATTERN = '.*[.]parquet'
  MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE FORCE = TRUE ON_ERROR = ABORT_STATEMENT;

TRUNCATE TABLE IF EXISTS MODEL_AGE_STATS;
COPY INTO MODEL_AGE_STATS FROM @EXPORTS_STAGE/model_age_stats/
  FILE_FORMAT = (FORMAT_NAME = PARQUET_FF) PATTERN = '.*[.]parquet'
  MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE FORCE = TRUE ON_ERROR = ABORT_STATEMENT;
