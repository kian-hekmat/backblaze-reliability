USE ROLE LOADER;
USE SECONDARY ROLES NONE;
USE WAREHOUSE LOAD_WH;
USE SCHEMA BACKBLAZE.GOLD;

CREATE TABLE IF NOT EXISTS DRIVE_LIFETIMES (
  SERIAL_NUMBER            VARCHAR NOT NULL,
  MODEL                    VARCHAR,
  MODEL_SHORT              VARCHAR,
  MANUFACTURER             VARCHAR,
  CAPACITY_BYTES           NUMBER(38,0),
  IS_DATA_DRIVE            BOOLEAN,
  FIRST_DATE               DATE,
  LAST_DATE                DATE,
  N_OBS_DAYS               NUMBER(38,0),
  OBSERVED_DAYS            NUMBER(38,0),
  FAILED                   NUMBER(1,0),
  FAILURE_DATE             DATE,
  CENSORED                 NUMBER(1,0),
  EVENT                    VARCHAR,
  LEFT_TRUNCATED           NUMBER(1,0),
  POH_FIRST                NUMBER(38,0),
  POH_LAST                 NUMBER(38,0),
  ENTRY_AGE_DAYS           FLOAT,
  EXIT_AGE_DAYS            FLOAT,
  AGE_OK                   NUMBER(1,0),
  N_FAILURE_ROWS           NUMBER(38,0),
  REAPPEARED_AFTER_FAILURE NUMBER(1,0),
  N_MODELS                 NUMBER(38,0),
  N_CAPACITIES             NUMBER(38,0),
  WINDOW_START             DATE,
  WINDOW_END               DATE
);

CREATE TABLE IF NOT EXISTS MODEL_PERIOD_STATS (
  MODEL          VARCHAR,
  MODEL_SHORT    VARCHAR,
  MANUFACTURER   VARCHAR,
  CAPACITY_BYTES NUMBER(38,0),
  IS_DATA_DRIVE  BOOLEAN,
  QUARTER        VARCHAR,
  DRIVE_COUNT    NUMBER(38,0),
  DRIVE_DAYS     NUMBER(38,0),
  FAILURES       NUMBER(38,0),
  MEAN_AGE_DAYS  FLOAT,
  PERIOD_START   DATE,
  PERIOD_END     DATE,
  AFR_PCT        FLOAT
);

CREATE TABLE IF NOT EXISTS MODEL_AGE_STATS (
  MODEL          VARCHAR,
  MODEL_SHORT    VARCHAR,
  MANUFACTURER   VARCHAR,
  CAPACITY_BYTES NUMBER(38,0),
  IS_DATA_DRIVE  BOOLEAN,
  QUARTER        VARCHAR,
  AGE_YEAR       NUMBER(38,0),
  DRIVE_COUNT    NUMBER(38,0),
  DRIVE_DAYS     NUMBER(38,0),
  FAILURES       NUMBER(38,0)
);
